"""
Общие константы бота.

Сюда вынесены значения, которые встречаются в нескольких модулях
(``bot/handlers.py``, ``bot/supervisor.py``, ``scheduler/main.py``,
``web/routers/pages.py``). Это позволяет избежать рассинхронизации
дефолтных шаблонов и магических чисел в коде.

ВАЖНО: значения дублируются в шаблонах Jinja (``web/templates/*.html``)
только тогда, когда фронту нужен предзаполненный ``placeholder``.
В таких случаях шаблон получает строку ``default_*`` через render-context
из ``web/routers/pages.py``, который импортирует константы отсюда.
"""

# ── Префикс payload в deep-link верификации ──────────────────────────────────
# Используется в URL вида ``https://max.ru/<bot>?start=verify_<token>`` —
# именно по этому префиксу handler ``_handle_bot_started`` понимает, что
# пользователь пришёл именно через капча-гейт, а не просто открыл бота.
VERIFY_PAYLOAD_PREFIX = "verify_"

# ── Параметры long-polling и backoff в supervisor ────────────────────────────
# Интервал между проверками БД на появление/удаление активных ботов.
# Низкое значение → быстрее реагируем на изменения, но больше нагрузки.
SUPERVISOR_REFRESH_INTERVAL = 30
# Server-side hang в /updates: MAX держит соединение до получения событий
# или истечения таймаута. Максимум по докам — 60 секунд.
SUPERVISOR_POLL_TIMEOUT = 25
# База exponential backoff при падении polling-задачи (5, 10, 20, 40… сек).
SUPERVISOR_RETRY_BASE = 5
# Потолок backoff — не ждём дольше 5 минут перед очередной попыткой.
SUPERVISOR_RETRY_MAX = 300

# ── Шаблоны сообщений верификации (captcha-gate) ─────────────────────────────
# Подставляются, если у пары/welcome-конфига не задан собственный текст.
