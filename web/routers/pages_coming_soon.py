def _make_handler(meta: dict):
    """Фабрика обработчиков для coming-soon страниц.

    Closure захватывает ``meta`` по значению, а не по ссылке —
    каждый вызов ``_make_handler`` создаёт новый замыкаемый словарь.
    """
    kwargs = {k: v for k, v in meta.items() if k != "path"}

    async def handler(request: Request, session: DBSession):
        user = await _require_user(request, session)
        return _coming_soon(request, user, **kwargs)

    # Уникальное имя функции нужно FastAPI для именования маршрутов
    handler.__name__ = f"{kwargs['active_page']}_page"
    return handler


for _meta in COMING_SOON_PAGES:
    router.get(_meta["path"], response_class=HTMLResponse)(
        _make_handler(_meta)
    )
